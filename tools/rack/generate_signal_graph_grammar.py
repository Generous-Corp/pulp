#!/usr/bin/env python3
"""Project the proven Rack patch-language token grammar into the C++ parser."""
import argparse
from pathlib import Path
import re
import patch_lang


def compact(pattern):
    # The shared verbose patterns keep comments after two spaces. Their
    # character classes contain no whitespace; quoted port contents do.
    return ''.join(re.sub(r'\s+', '', line.split('  #', 1)[0])
                   for line in pattern.splitlines())


def generate():
    patterns = {'declaration': patch_lang.DECL.pattern,
                'endpoint': compact(patch_lang.ENDPOINT.pattern),
                'setting': compact(patch_lang.SETTING.pattern)}
    return ('// Generated by tools/rack/generate_signal_graph_grammar.py; do not edit.\n'
            '#pragma once\nnamespace pulp::host::patch_grammar {\n' +
            ''.join(f'inline constexpr char {key}[] =\n    R"grammar({value})grammar";\n'
                    for key, value in patterns.items()) + '} // namespace pulp::host::patch_grammar\n')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    target = Path(__file__).resolve().parents[2] / 'core/host/src/graph_patch_grammar.hpp'
    content = generate()
    if args.check:
        if target.read_text() != content:
            raise SystemExit('SignalGraph grammar differs from patch_lang.py; regenerate it')
    else:
        target.write_text(content)
