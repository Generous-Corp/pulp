#!/usr/bin/env python3
"""Project the proven Rack patch-language token grammar into the C++ parser."""
import argparse
import ast
from pathlib import Path
import re


def compact(pattern):
    # The shared verbose patterns keep comments after two spaces. Their
    # character classes contain no whitespace; quoted port contents do.
    return ''.join(re.sub(r'\s+', '', line.split('  #', 1)[0])
                   for line in pattern.splitlines())


def generate():
    # Read only constant token patterns, without executing Rack's runtime imports.
    source = (Path(__file__).resolve().parents[2] / 'tools/rack/patch_lang.py').read_text(encoding="utf-8")
    tokens = {}
    def constant(node):
        if isinstance(node, ast.Constant) and isinstance(node.value, str):
            return node.value
        if isinstance(node, ast.Name):
            return tokens[node.id]
        if isinstance(node, ast.BinOp) and isinstance(node.op, ast.Add):
            return constant(node.left) + constant(node.right)
        raise ValueError('grammar uses an unsupported nonconstant expression')
    for statement in ast.parse(source).body:
        if not isinstance(statement, ast.Assign) or len(statement.targets) != 1:
            continue
        name = getattr(statement.targets[0], 'id', '')
        if name not in ('PORT_TOKEN', 'DECL', 'ENDPOINT', 'SETTING'):
            continue
        call = statement.value
        if name == 'PORT_TOKEN':
            tokens[name] = constant(call)
            continue
        if not isinstance(call, ast.Call) or not call.args:
            raise ValueError(f'{name} is no longer a constant compiled token pattern')
        tokens[name] = constant(call.args[0])
    patterns = {'declaration': tokens['DECL'],
                'endpoint': compact(tokens['ENDPOINT']),
                'setting': compact(tokens['SETTING'])}
    return ('// Generated by tools/rack/generate_signal_graph_grammar.py; do not edit.\n'
            '#pragma once\nnamespace pulp::host::patch_grammar {\n' +
            ''.join(f'inline constexpr char {key}[] =\n    R"grammar({value})grammar";\n'
                    for key, value in patterns.items()) + '} // namespace pulp::host::patch_grammar\n')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    target = Path(__file__).resolve().parents[2] / 'core/host/src/graph_patch_grammar.hpp'
    content = generate()
    if args.check:
        if target.read_text(encoding="utf-8") != content:
            raise SystemExit('SignalGraph grammar differs from patch_lang.py; regenerate it')
    else:
        target.write_text(content, encoding="utf-8")
