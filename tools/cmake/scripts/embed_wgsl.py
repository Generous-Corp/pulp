#!/usr/bin/env python3
"""Embed one WGSL file as a C++ string constant for `pulp_add_wgsl_shaders`.

The CMake function runs this once per shader through
`add_custom_command(OUTPUT ... DEPENDS ...)`, so the header is regenerated only
when the shader (or this script) changes. The output is

    #pragma once
    #include <string_view>
    namespace NAMESPACE {
    inline constexpr char VAR_data[] = { 0x.., ..., 0x00 };
    inline constexpr std::string_view VAR{VAR_data, N};
    }

The source is stored as a byte array rather than a raw string literal because
MSVC caps a single string literal at about 16 KB, and a shader is plain text
of any length. The array is NUL-terminated, so `VAR.data()` is also a C
string.
"""

from __future__ import annotations

import argparse
import pathlib
import sys


def render(source: bytes, namespace: str, var: str, origin: str) -> str:
    lines = [
        "// Generated by pulp_add_wgsl_shaders from " + origin + ". Do not edit.",
        "#pragma once",
        "",
        "#include <string_view>",
        "",
        f"namespace {namespace} {{",
        "",
        f"inline constexpr char {var}_data[] = {{",
    ]
    data = list(source) + [0]
    for start in range(0, len(data), 16):
        chunk = ", ".join(f"0x{byte:02x}" for byte in data[start:start + 16])
        lines.append(f"    {chunk},")
    lines.append("};")
    lines.append(
        f"inline constexpr std::string_view {var}{{{var}_data, {len(source)}}};")
    lines.append("")
    lines.append(f"}} // namespace {namespace}")
    lines.append("")
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--src", required=True, type=pathlib.Path)
    parser.add_argument("--out", required=True, type=pathlib.Path)
    parser.add_argument("--namespace", required=True)
    parser.add_argument("--var", required=True)
    args = parser.parse_args(argv)

    source = args.src.read_bytes()
    if b"\0" in source:
        print(f"{args.src}: WGSL source contains a NUL byte", file=sys.stderr)
        return 1
    text = render(source, args.namespace, args.var, args.src.name)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    # Leave an unchanged header untouched so dependents do not rebuild.
    if args.out.exists() and args.out.read_text(encoding="utf-8") == text:
        return 0
    args.out.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
