#include <pulp/state/store.hpp>
#include <pulp/view/js_engine.hpp>
#include <pulp/view/scripted_ui.hpp>
#include <pulp/view/view.hpp>

#include "bytecode_probe_data.hpp"

#include <cstdint>
#include <iostream>
#include <string>
#include <vector>

int main() {
    using namespace pulp::view;

    std::vector<std::uint8_t> corrupt(bytecode_probe::bytecode_probe_js_pjsbc,
                                      bytecode_probe::bytecode_probe_js_pjsbc +
                                          bytecode_probe::bytecode_probe_js_pjsbc_size);
    if (corrupt.size() < 8) {
        std::cerr << "installed bytecode probe: generated blob is unexpectedly small\n";
        return 1;
    }
    corrupt[0] ^= 0xff;
    if (register_embedded_script_bytecode(corrupt.data(), corrupt.size())) {
        std::cerr << "installed bytecode probe: corrupt bytecode was accepted\n";
        return 1;
    }

    if (!register_embedded_script_bytecode(bytecode_probe::bytecode_probe_js_pjsbc,
                                           bytecode_probe::bytecode_probe_js_pjsbc_size)) {
        std::cerr << "installed bytecode probe: generated bytecode was refused\n";
        return 1;
    }

    View root;
    root.set_bounds({0, 0, 320, 240});
    state::StateStore store;
    ScriptedUiSession session(root, store,
                              {.enable_hot_reload = false,
                               .enable_theme_reload = false,
                               .script_source = "createLabel('bytecode-probe', 'ok', '');",
                               .script_name = "bytecode-probe.js"});
    std::string error;
    if (!session.load(&error)) {
        std::cerr << "installed bytecode probe: scripted session failed: " << error << '\n';
        return 1;
    }
    if (!session.bridge() || !session.bridge()->widget("bytecode-probe")) {
        std::cerr << "installed bytecode probe: scripted session did not mount the label\n";
        return 1;
    }
    if (script_bytecode_cache_stats().embedded == 0) {
        std::cerr
            << "installed bytecode probe: scripted session compiled instead of loading bytecode\n";
        return 1;
    }
    return 0;
}
