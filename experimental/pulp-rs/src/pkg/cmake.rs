//! Generate `cmake/pulp-packages.cmake` from the lock file + registry.
//!
//! # Scope
//!
//! This module is a *pure* renderer — it doesn't touch the filesystem
//! itself. The C++ reference lives in `package_commands_util.cpp::
//! generate_packages_cmake` and `generate_cmake_block`.
//!
//! # Output shape
//!
//! The file opens with the shared verifier from
//! `tools/packages/pulp-packages-verify.cmake`, then one block per locked
//! package, fetched by the full commit recorded in `packages.lock.json`:
//!
//! ```cmake
//! # ── alac (c38887c5) ──
//! if(COMMAND pulp_register_fetchcontent_source)
//!   pulp_register_fetchcontent_source(alac REF c38887c5c5e64a4b31108733bd79ca9b2496d987)
//! endif()
//! FetchContent_Declare(alac
//!   GIT_REPOSITORY https://github.com/macosforge/alac.git
//!   GIT_TAG        c38887c5c5e64a4b31108733bd79ca9b2496d987
//!   SOURCE_SUBDIR  pulp-package-populate-only
//! )
//! _pulp_package_make_available(alac c38887c5... sha256-... ON)
//! # ── end alac ──
//! ```
//!
//! A lock entry without a full commit and integrity (written before
//! packages were pinned) keeps the old fetch-by-tag block behind a
//! configure-time warning until `pulp update --apply` re-pins it.
//!
//! Header-only packages declare an INTERFACE target and
//! `target_include_directories` the fetched source.

use crate::pkg::pin;
use crate::pkg::registry::{LockFile, LockedPackage, PackageDescriptor, Registry};

/// Shared `CMake` verifier emitted at the top of every generated file. The
/// C++ generator embeds the same text; both are tested against this file.
pub const VERIFY_PREAMBLE: &str =
    include_str!("../../../../tools/packages/pulp-packages-verify.cmake");

/// Render `cmake/pulp-packages.cmake` from `lock` + `reg`.
///
/// Packages in the lock file that aren't in the registry are skipped
/// (matches C++ behavior). Ordering follows the lock file's
/// `BTreeMap` natural order — alphabetical by id.
#[must_use]
pub fn generate_packages_cmake(lock: &LockFile, reg: &Registry) -> String {
    let mut out = String::new();
    out.push_str("# Auto-generated by pulp package manager — do not edit manually\n");
    out.push_str("# Run 'pulp add <pkg>' or 'pulp remove <pkg>' to modify\n");
    out.push_str("include(FetchContent)\n");
    out.push_str(VERIFY_PREAMBLE);
    out.push('\n');
    for (id, locked) in &lock.packages {
        let Some(pkg) = reg.packages.get(id) else {
            continue;
        };
        out.push_str(&generate_block(pkg, locked, None));
        out.push('\n');
    }
    out
}

fn push_fetch(out: &mut String, pkg: &PackageDescriptor, locked: &LockedPackage, indent: &str) {
    use std::fmt::Write as _;
    if pin::is_pinned(&locked.commit, &locked.integrity) {
        let repository = if locked.resolved.is_empty() {
            pkg.fetch.git_repository.as_str()
        } else {
            locked.resolved.as_str()
        };
        let _ = writeln!(out, "{indent}if(COMMAND pulp_register_fetchcontent_source)");
        let _ = writeln!(
            out,
            "{indent}  pulp_register_fetchcontent_source({} REF {})",
            pkg.id, locked.commit
        );
        let _ = writeln!(out, "{indent}endif()");
        let _ = writeln!(out, "{indent}FetchContent_Declare({}", pkg.id);
        let _ = writeln!(out, "{indent}  GIT_REPOSITORY {repository}");
        let _ = writeln!(out, "{indent}  GIT_TAG        {}", locked.commit);
        let _ = writeln!(out, "{indent}  SOURCE_SUBDIR  pulp-package-populate-only");
        let _ = writeln!(out, "{indent})");
        let _ = writeln!(
            out,
            "{indent}_pulp_package_make_available({} {} {} ON)",
            pkg.id, locked.commit, locked.integrity
        );
    } else {
        let _ = writeln!(
            out,
            "{indent}message(WARNING \"Pulp package {} is not pinned in packages.lock.json \
             (no full commit + integrity); it is fetched by mutable tag. Run 'pulp update \
             --apply' to pin it.\")",
            pkg.id
        );
        let _ = writeln!(out, "{indent}FetchContent_Declare({}", pkg.id);
        let _ = writeln!(out, "{indent}  GIT_REPOSITORY {}", pkg.fetch.git_repository);
        let _ = writeln!(out, "{indent}  GIT_TAG        {}", pkg.fetch.git_tag);
        let _ = writeln!(out, "{indent}  GIT_SHALLOW    TRUE");
        let _ = writeln!(out, "{indent})");
        let _ = writeln!(out, "{indent}FetchContent_MakeAvailable({})", pkg.id);
    }
}

/// Render a single `FetchContent` block for `pkg` pinned by `locked`.
///
/// When `guard_platform` is `Some("macOS")` / `"Windows"` / `"Linux"`,
/// the block is wrapped in the matching `if(APPLE)` / `if(WIN32)` /
/// `if(UNIX AND NOT APPLE)` guard and gets a
/// `target_compile_definitions(... PULP_HAS_<ID>=1)` flag.
#[must_use]
pub fn generate_block(
    pkg: &PackageDescriptor,
    locked: &LockedPackage,
    guard_platform: Option<&str>,
) -> String {
    use std::fmt::Write as _;
    let guarded = guard_platform.is_some();
    let indent = if guarded { "  " } else { "" };
    let mut out = String::new();
    let _ = write!(out, "# ── {} ({}) ", pkg.id, pkg.version);
    if let Some(p) = guard_platform {
        let _ = write!(out, "[{p} only] ");
    }
    out.push_str("──\n");

    if let Some(p) = guard_platform {
        match p {
            "macOS" => out.push_str("if(APPLE)\n"),
            "Windows" => out.push_str("if(WIN32)\n"),
            "Linux" => out.push_str("if(UNIX AND NOT APPLE)\n"),
            _ => {}
        }
    }

    push_fetch(&mut out, pkg, locked, indent);

    if pkg.fetch.method == "header-only" {
        if let Some(target) = pkg.cmake.targets.first() {
            out.push_str(indent);
            let _ = writeln!(out, "add_library({target} INTERFACE)");
            out.push_str(indent);
            let _ = write!(
                out,
                "target_include_directories({} INTERFACE ${{{}_SOURCE_DIR}}",
                target, pkg.id
            );
            if !pkg.cmake.include_dir.is_empty() && pkg.cmake.include_dir != "." {
                out.push('/');
                out.push_str(&pkg.cmake.include_dir);
            }
            out.push_str(")\n");
        }
    }

    if guarded {
        let upper = pkg
            .id
            .chars()
            .map(|c| {
                if c == '-' {
                    '_'
                } else {
                    c.to_ascii_uppercase()
                }
            })
            .collect::<String>();
        let _ = writeln!(
            out,
            "  target_compile_definitions(${{PROJECT_NAME}} PRIVATE PULP_HAS_{upper}=1)"
        );
        out.push_str("endif()\n");
    }

    let _ = writeln!(out, "# ── end {} ──", pkg.id);
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::pkg::registry::{CMakeInfo, FetchInfo, LockedPackage};
    use std::collections::BTreeMap;

    const COMMIT: &str = "c38887c5c5e64a4b31108733bd79ca9b2496d987";

    fn integrity() -> String {
        format!("sha256-{}", "ab".repeat(32))
    }

    fn alac_pkg() -> PackageDescriptor {
        PackageDescriptor {
            id: "alac".to_owned(),
            name: "Apple ALAC".to_owned(),
            version: "c38887c5".to_owned(),
            fetch: FetchInfo {
                method: "FetchContent".to_owned(),
                git_repository: "https://example.com/alac.git".to_owned(),
                git_tag: "v1.0".to_owned(),
            },
            cmake: CMakeInfo {
                targets: vec!["alac".to_owned()],
                header_only: false,
                include_dir: String::new(),
            },
            ..PackageDescriptor::default()
        }
    }

    fn pinned() -> LockedPackage {
        LockedPackage {
            version: "c38887c5".to_owned(),
            resolved: "https://example.com/locked-alac.git".to_owned(),
            integrity: integrity(),
            commit: COMMIT.to_owned(),
            ..LockedPackage::default()
        }
    }

    #[test]
    fn pinned_block_fetches_the_locked_commit_not_the_registry_tag() {
        let s = generate_block(&alac_pkg(), &pinned(), None);
        assert!(s.contains("FetchContent_Declare(alac"));
        assert!(s.contains("GIT_REPOSITORY https://example.com/locked-alac.git"));
        assert!(s.contains(&format!("GIT_TAG        {COMMIT}")));
        assert!(
            !s.contains("v1.0"),
            "registry tag must not reach the fetch:\n{s}"
        );
        assert!(
            !s.contains("GIT_SHALLOW"),
            "a commit fetch cannot be shallow:\n{s}"
        );
        assert!(s.contains("SOURCE_SUBDIR  pulp-package-populate-only"));
        assert!(s.contains(&format!(
            "_pulp_package_make_available(alac {COMMIT} {} ON)",
            integrity()
        )));
        assert!(s.contains(&format!(
            "pulp_register_fetchcontent_source(alac REF {COMMIT})"
        )));
        assert!(s.contains("# ── end alac ──"));
    }

    #[test]
    fn unpinned_legacy_entry_warns_and_keeps_tag_fetch() {
        let legacy = LockedPackage {
            version: "1.0".to_owned(),
            resolved: "https://example.com/alac.git".to_owned(),
            integrity: String::new(),
            commit: "master".to_owned(),
            ..LockedPackage::default()
        };
        let s = generate_block(&alac_pkg(), &legacy, None);
        assert!(s.contains("message(WARNING \"Pulp package alac is not pinned"));
        assert!(s.contains("GIT_TAG        v1.0"));
        assert!(!s.contains("_pulp_package_make_available"));
    }

    #[test]
    fn generated_file_embeds_the_shared_verifier() {
        let mut lock = LockFile::default();
        lock.packages.insert("alac".to_owned(), pinned());
        let mut packages = BTreeMap::new();
        packages.insert("alac".to_owned(), alac_pkg());
        let reg = Registry {
            version: 1,
            packages,
        };
        let s = generate_packages_cmake(&lock, &reg);
        assert!(s.contains(VERIFY_PREAMBLE));
        assert!(VERIFY_PREAMBLE.contains("function(_pulp_package_verify"));
        assert!(VERIFY_PREAMBLE.contains("integrity mismatch"));
        let listing = pin::TREE_LISTING_ARGS.join(" ");
        assert!(
            VERIFY_PREAMBLE.contains(&listing),
            "verifier must hash `git {listing}` like the CLI does"
        );
    }

    #[test]
    fn block_with_macos_guard_wraps_in_apple_if() {
        let s = generate_block(&alac_pkg(), &pinned(), Some("macOS"));
        assert!(s.contains("if(APPLE)"));
        assert!(s.contains("endif()"));
        assert!(s.contains("PULP_HAS_ALAC=1"));
        assert!(s.contains(&format!("  GIT_TAG        {COMMIT}")));
    }

    #[test]
    fn block_with_header_only_fetch_adds_interface_target() {
        let mut pkg = alac_pkg();
        pkg.fetch.method = "header-only".to_owned();
        pkg.cmake.include_dir = "include".to_owned();
        let s = generate_block(&pkg, &pinned(), None);
        assert!(s.contains("add_library(alac INTERFACE)"));
        assert!(s.contains("target_include_directories(alac INTERFACE ${alac_SOURCE_DIR}/include)"));
    }

    #[test]
    fn generator_skips_packages_not_in_registry() {
        let mut lock = LockFile::default();
        lock.packages.insert(
            "ghost".to_owned(),
            LockedPackage {
                version: "1.0".to_owned(),
                ..LockedPackage::default()
            },
        );
        let reg = Registry {
            version: 1,
            packages: BTreeMap::new(),
        };
        let s = generate_packages_cmake(&lock, &reg);
        assert!(s.contains("include(FetchContent)"));
        assert!(!s.contains("ghost"));
    }

    #[test]
    fn guarded_id_with_dash_is_uppercased_and_underscored() {
        let mut pkg = alac_pkg();
        pkg.id = "foo-bar".to_owned();
        let s = generate_block(&pkg, &pinned(), Some("Windows"));
        assert!(s.contains("PULP_HAS_FOO_BAR=1"));
    }
}
